//! `text.rs` 私有的 Unicode 17.0 属性区间表与 RGI emoji 列表（生成数据，禁止手改）。
//!
//! # 为什么需要这个模块
//!
//! 宽度计算、零宽/不可打印判定、CJK 断行与 `Intl.Segmenter("word")` 的模拟都要与 TS 版在
//! Node 26.12.1 / ICU 78.3 上的逐码点行为一致。`unicode-width` 的算法与它不同，
//! `regex` 内置的 `\p{...}` 属性表也是更旧的 Unicode 版本（具体漏掉的码点见
//! `text.rs` 的 `cjk_break_regex` 文档），直接用会让字符宽度、断行位置和词边界漂移。
//! 因此这里把需要的属性以**区间表**形式内嵌为静态数组：单字符查询只做内存二分，
//! CJK 两张表还会在首次使用时拼成正则字符类（见下文），两者都不调用 ICU，
//! 也不在运行时读取外部属性数据。
//!
//! # 数据形状与不变量
//!
//! ```text
//! (u32, u32)      闭区间 [start, end]；按 start 升序，互不重叠
//! (u32, u32, u8)  WORD_BREAK_RANGES：区间 + Word_Break 类 id（第三列）
//! &str            RGI_EMOJI：完整 emoji 串；按 UTF-8 字节序升序
//! ```
//!
//! 消费方 `text.rs` 的 `range_contains`、`word_break_class`、`is_rgi_emoji` 全部用二分查找，
//! 所以**升序、互不重叠、闭区间**是硬约束：一旦顺序或重叠关系被破坏，查询会静默返回错误
//! 结果（不 panic、不报错），表现为宽度、断行或词边界与 Node 不一致。
//!
//! `FULLWIDTH_MIN` / `FULLWIDTH_MAX` / `WIDE_MIN` / `WIDE_MAX` 是 `east_asian_width` 的
//! 快路径边界：码点落在 [MIN, MAX] 之外时直接按宽度 1 返回、不再查表。它们必须分别覆盖
//! `FULLWIDTH_RANGES` / `WIDE_RANGES` 的最小与最大码点，否则边界外的宽字符会被误判为 1 列。
//!
//! # 谁在用
//!
//! 本文件由 `text.rs` 以 `#[path = "text_tables.rs"] mod text_tables;` 声明为**私有子模块**，
//! crate 内只有 `text.rs` 引用它；各项虽标为 `pub(crate)`，模块路径在 `text` 之外不可达，
//! 因此不属于 crate 的公开 API。按 `text.rs` 中的消费方分组：
//!
//! - `FULLWIDTH_RANGES` / `WIDE_RANGES` 及四个 MIN/MAX 常量：`east_asian_width`。
//! - `DI_RANGES` / `CONTROL_RANGES` / `FORMAT_RANGES` / `MARK_RANGES`：
//!   零宽与不可打印字符判定（`is_default_ignorable`、`is_control`、`is_format`、
//!   `is_mark`）。
//! - `MC_RANGES`：`is_spacing_mark`，唯一调用点是 `is_terminal_spacing_mark_char`（即
//!   `terminalSpacingMarkRegex` 的间距标记判定，`grapheme_width` 也复用该函数）。这些字符
//!   **占格**，不属于零宽/不可打印判定：整簇都是间距标记时按 `chars().count()` 计列，
//!   簇内位于基字之后时逐个加 1 列（均见 `text.rs` 的 `grapheme_width`）。
//! - `RGI_EMOJI`：`is_rgi_emoji`，对**整个字素簇**做精确匹配（调用方 `grapheme_width`
//!   先用 `could_be_emoji` 过滤）。
//! - `CJK_BREAK_RANGES` / `CJK_PUNCTUATION_RANGES`：单字符判定 `is_cjk_break_char` /
//!   `is_cjk_punctuation`，同时被拼成 `cjk_break_regex` / `cjk_punctuation_regex` 的字符类；
//!   区间表是这两条路径的唯一事实来源，改表会同时影响两者。
//! - `WORD_BREAK_RANGES`：`word_break_class`；第三列的 id 与 `text.rs` 内私有 `wb` 模块的
//!   常量对应（0 = Other，表中不出现）。
//! - `EXTENDED_PICTOGRAPHIC_RANGES` / `IDEOGRAPHIC_RANGES` / `COMPLEX_CONTEXT_RANGES` /
//!   `GCB_CONTROL_RANGES`：ICU `word.txt` 规则引擎的字符类。
//! - `HAN_SCRIPT_RANGES` / `HIRAGANA_SCRIPT_RANGES` / `KATAKANA_SCRIPT_RANGES`：
//!   三者都是 `\p{Script=...}` 判定（`text.rs` 的 `is_script_han` / `is_script_hiragana` /
//!   `is_script_katakana`），并都参与词典引擎的字符集判定：`is_cjk_dictionary_char` 与
//!   `default_word_segments` 的 `scripted_cjk`。区别是前两张表还参与 `is_kana_kanji`
//!   （`$Han` / `$Hiragana`），而 `KATAKANA_SCRIPT_RANGES` 不参与：`is_kana_kanji` 里的
//!   `$Katakana` 来自 `word_break_class(cp) == wb::KATAKANA`（`WORD_BREAK_RANGES` 的
//!   class 9，比 `[:Katakana:]` 多出 `ー` / `゛` / `゜` 等 `Script=Common` 字符）。
//! - `THAI_SCRIPT_RANGES` / `LAO_SCRIPT_RANGES` / `KHMER_SCRIPT_RANGES` /
//!   `MYANMAR_SCRIPT_RANGES`：四个 SA 词典引擎的脚本归属（`sea_dictionary_script`）。
//! - `COMMON_SCRIPT_RANGES`：`is_common_script`；用途见该静态项上的说明
//!   （`UnhandledEngine` 的 Script 记忆效应）。
//!
//! # 生成来源与修改禁忌
//!
//! 文件内有两处以 `Generated` 开头的代码注释块（`// Generated …`），连同部分静态项上的
//! `///` 记录来源与版本：
//! - 紧随其后的第一处按分组概括来源：EAW 表来自 `get-east-asian-width@1.6.0` 的
//!   `lookup-data.js`；RGI_EMOJI 由 Node 26.12.1 / ICU 78.3 的 `\p{RGI_Emoji}` 枚举得到；
//!   CJK 断行两张表由 `cjkBreakRegex` / `cjkPunctuationRegex` 的单字符测试枚举得到；
//!   `WORD_BREAK_RANGES etc.` 一行指向 Unicode 17.0 的 Word_Break / Extended_Pictographic /
//!   Ideographic / LineBreak / GCB / Script 属性。
//! - `WORD_BREAK_RANGES` 上方的第二处（`Generated from the Unicode 17.0.0 UCD`）才列出具体
//!   UCD 文件：`WordBreakProperty.txt` / `Scripts.txt` / `PropList.txt` / `emoji-data.txt` /
//!   `LineBreak.txt` / `GraphemeBreakProperty.txt`；该块之后的部分静态项在 `///` 里注明
//!   对应属性（如 `\p{Script=Han}`）。
//! - 重新生成必须使用**相同版本**的数据源，并保持上面的排序与区间形状；否则与 TS 的逐码点
//!   对齐会破裂。表体不要手工增删条目——单条区间改动就能让二分查找漏判它覆盖的整段码点。
// ===========================================================================
// Generated tables. Do not edit by hand.
//
// * EAW ranges: get-east-asian-width@1.6.0 `lookup-data.js` (Unicode 17.0).
// * RGI_EMOJI: every string the JS `\p{RGI_Emoji}` regex accepts, extracted from
//   Node 26.12.1 / ICU 78.3 by enumeration, sorted by UTF-8 bytes.
// * CJK_BREAK_RANGES / CJK_PUNCTUATION_RANGES: code points matched by the
//   `cjkBreakRegex` / `cjkPunctuationRegex` single-character tests (enumerated).
// * WORD_BREAK_RANGES etc.: Unicode 17.0 properties used by the ICU `word.txt`
//   rule engine in `text.rs` (Word_Break, Extended_Pictographic, Ideographic,
//   LineBreak=Complex_Context, GCB=Control, Script=Han/Hiragana/Katakana).
// ===========================================================================

